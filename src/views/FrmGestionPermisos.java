    private void guardarPermiso() {
        try {
            String rol = (String) cmbRol.getSelectedItem();
            String modulo = (String) cmbModulo.getSelectedItem();
            boolean puedeVer = chbPuedeVer.isSelected();
            boolean puedeOperar = chbPuedeOperar.isSelected();

            if (rol == null || modulo == null) {
                mostrarMensaje("advertencia", "Seleccione un rol y un módulo.");
                return;
            }

            // "Todos" = null (global), otherwise use selected department ID
            Integer idDepartamento = null;
            Object deptoSel = cmbDepartamento.getSelectedItem();
            if (deptoSel != null && !"Todos".equals(deptoSel.toString())) {
                // Look up department ID by name
                idDepartamento = buscarIdDepartamento(deptoSel.toString());
            }

            String resultado;
            if (editando) {
                resultado = controller.actualizar(new models.Permiso(permisoEnEdicion, rol, idDepartamento, modulo, puedeVer, puedeOperar));
            } else {
                resultado = controller.guardar(new models.Permiso(0, rol, idDepartamento, modulo, puedeVer, puedeOperar));
            }
            mostrarMensaje("exito", resultado);
            cargarTabla();
            limpiar();
        } catch (Exception e) {
            mostrarMensaje("error", "Error: " + e.getMessage());
        }
    }

    private void eliminarPermiso() {
        try {
            int fila = tblPermisos.getSelectedRow();
            if (fila == -1) {
                mostrarMensaje("advertencia", "Seleccione un permiso.");
                return;
            }
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblPermisos.getModel();
            int id = (int) model.getValueAt(fila, 0);
            String info = model.getValueAt(fila, 1) + " - " + model.getValueAt(fila, 3);
            if (mostrarConfirmacion("¿Eliminar permiso '" + info + "'?")) {
                mostrarMensaje("exito", controller.eliminar(id));
                cargarTabla();
                limpiar();
            }
        } catch (Exception e) {
            mostrarMensaje("error", "Error al eliminar permiso: " + e.getMessage());
        }
    }

    private void seleccionarPermiso() {
        if (tblPermisos.getSelectedRow() == -1) return;
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblPermisos.getModel();
        int fila = tblPermisos.getSelectedRow();
        permisoEnEdicion = (int) model.getValueAt(fila, 0);
        cmbRol.setSelectedItem(model.getValueAt(fila, 1));
        cmbModulo.setSelectedItem(model.getValueAt(fila, 3));
        chbPuedeVer.setSelected((boolean) model.getValueAt(fila, 4));
        chbPuedeOperar.setSelected((boolean) model.getValueAt(fila, 5));
        // Set department combo: "Todos" for null, otherwise department name
        String depto = model.getValueAt(fila, 2).toString();
        cmbDepartamento.setSelectedItem(depto);
        editando = true;
        btnGuardar.setText("Actualizar");
    }

    private void cargarTabla() {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Rol");
        modelo.addColumn("Departamento");
        modelo.addColumn("Módulo");
        modelo.addColumn("Puede Ver");
        modelo.addColumn("Puede Operar");
        if (controller != null) {
            controller.listar().forEach(p -> modelo.addRow(new Object[]{
                p.getIdPermiso(), p.getRol(),
                p.getIdDepartamento() != null ? p.getIdDepartamento() : "Todos",
                p.getModulo(), p.isPuedeVer(), p.isPuedeOperar()
            }));
        }
        tblPermisos.setModel(modelo);
    }

    private void limpiar() {
        cmbRol.setSelectedIndex(-1);
        cmbModulo.setSelectedIndex(-1);
        chbPuedeVer.setSelected(false);
        chbPuedeOperar.setSelected(false);
        cmbDepartamento.setSelectedIndex(0); // "Todos" = global
        tblPermisos.clearSelection();
        editando = false;
        permisoEnEdicion = 0;
        btnGuardar.setText("Guardar");
        cmbRol.requestFocus();
    }

    private void configurarComponentes() {
        tblPermisos.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) { seleccionarPermiso(); }
        });
        // Load departments into combo: "Todos" = global, then each department
        cmbDepartamento.removeAllItems();
        cmbDepartamento.addItem("Todos");
        new controllers.DepartamentoController().listar()
            .forEach(d -> cmbDepartamento.addItem(d.getNombre()));
        cargarTabla();
    }

    /**
     * Looks up a department ID by its name.
     * @return department ID, or null if not found
     */
    private Integer buscarIdDepartamento(String nombre) {
        return new controllers.DepartamentoController().listar().stream()
            .filter(d -> d.getNombre().equals(nombre))
            .findFirst()
            .map(models.Departamento::getIdDepartamento)
            .orElse(null);
    }

    public void mostrarMensaje(String tipo, String mensaje) {
        int type;
        String title;
        switch (tipo) {
            case "exito":
                type = javax.swing.JOptionPane.INFORMATION_MESSAGE;
                title = "Éxito";
                break;
            case "error":
                type = javax.swing.JOptionPane.ERROR_MESSAGE;
                title = "Error";
                break;
            case "advertencia":
                type = javax.swing.JOptionPane.WARNING_MESSAGE;
                title = "Advertencia";
                break;
            default:
                type = javax.swing.JOptionPane.INFORMATION_MESSAGE;
                title = "Información";
        }
        javax.swing.JOptionPane.showMessageDialog(this, mensaje, title, type);
    }

    public boolean mostrarConfirmacion(String mensaje) {
        return javax.swing.JOptionPane.showConfirmDialog(this, mensaje, "Confirmar",
            javax.swing.JOptionPane.YES_NO_OPTION) == javax.swing.JOptionPane.YES_OPTION;
    }

