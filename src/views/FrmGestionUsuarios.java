    private void inicializarPersonalizaciones() {
        // Configurar columnas de la tabla
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Username");
        modelo.addColumn("Rol");
        modelo.addColumn("Empleado");
        modelo.addColumn("Estado");
        tblUsuarios.setModel(modelo);

        // Configurar combos
        cmbRol.setModel(new javax.swing.DefaultComboBoxModel<>(new String[]{"Admin", "RRHH", "Empleado"}));
        cargarComboEmpleados();

        // SVG icons
        utils.UIStyles.setSVGIcon(btnGuardar, "Save");
        utils.UIStyles.setSVGIcon(btnNuevo, "Plus");
        utils.UIStyles.setSVGIcon(btnDesactivar, "Ban");
        utils.UIStyles.setSVGIcon(btnReactivar, "Undo");

        // Row selection listener
        tblUsuarios.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                seleccionarUsuario();
            }
        });

        // Estado inicial
        toggleFormulario(false);
        cargarTabla();
    }

    private void cargarComboEmpleados() {
        cmbEmpleado.removeAllItems();
        try {
            controller.obtenerEmpleadosSinUsuario().forEach(e ->
                cmbEmpleado.addItem(e.getIdEmpleado() + " - " + e.getNombres() + " " + e.getApellidos())
            );
        } catch (Exception e) {
            mostrarMensaje("error", "Error al cargar empleados: " + e.getMessage());
        }
    }

    private int getIdEmpleadoDesdeCombo() {
        String sel = (String) cmbEmpleado.getSelectedItem();
        if (sel == null || sel.isEmpty()) return 0;
        return Integer.parseInt(sel.split(" - ")[0]);
    }

