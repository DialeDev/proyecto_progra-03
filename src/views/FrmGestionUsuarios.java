    private void cargarTabla() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblUsuarios.getModel();
        model.setRowCount(0);
        try {
            controller.listarUsuarios().forEach(u -> model.addRow(new Object[]{
                u.getIdUsuario(),
                u.getUsername(),
                u.getRol(),
                u.getNombreEmpleado() != null ? u.getNombreEmpleado() : "",
                u.isActivo() ? "Activo" : "Inactivo"
            }));
        } catch (Exception e) {
            mostrarMensaje("error", "Error al cargar usuarios: " + e.getMessage());
        }
    }

    private void limpiarFormulario() {
        editando = false;
        usuarioEnEdicion = 0;
        txtUsername.setText("");
        txtPassword.setText("");
        chkActivo.setSelected(true);
        cmbRol.setSelectedIndex(-1);
        cmbEmpleado.setSelectedIndex(-1);
        btnGuardar.setText("Guardar");
        tblUsuarios.clearSelection();
    }

    private void toggleFormulario(boolean visible) {
        // Show/hide the edit panel area (combos, text fields, check, save button)
        txtUsername.setVisible(visible);
        txtPassword.setVisible(visible);
        cmbRol.setVisible(visible);
        cmbEmpleado.setVisible(visible);
        chkActivo.setVisible(visible);
        btnGuardar.setVisible(visible);
        if (!visible) limpiarFormulario();
    }

    private void guardarUsuario() {
        String username = txtUsername.getText().trim();
        String password = txtPassword.getText().trim();
        String rol = (String) cmbRol.getSelectedItem();
        int idEmpleado = getIdEmpleadoDesdeCombo();

        if (username.isEmpty()) {
            mostrarMensaje("advertencia", "El username es obligatorio.");
            return;
        }
        if (!editando && password.isEmpty()) {
            mostrarMensaje("advertencia", "La contraseña es obligatoria para nuevos usuarios.");
            return;
        }
        if (rol == null) {
            mostrarMensaje("advertencia", "Seleccione un rol.");
            return;
        }
        if (idEmpleado == 0) {
            mostrarMensaje("advertencia", "Seleccione un empleado.");
            return;
        }

        try {
            if (editando) {
                controller.editarUsuario(usuarioEnEdicion, username, rol, idEmpleado, chkActivo.isSelected());
                mostrarMensaje("exito", "Usuario actualizado.");
            } else {
                controller.crearUsuario(username, password, rol, idEmpleado);
                mostrarMensaje("exito", "Usuario creado.");
            }
            cargarTabla();
            toggleFormulario(false);
            cargarComboEmpleados();
        } catch (Exception e) {
            mostrarMensaje("error", "Error: " + e.getMessage());
        }
    }

    private void desactivarUsuario() {
        int fila = tblUsuarios.getSelectedRow();
        if (fila == -1) {
            mostrarMensaje("advertencia", "Seleccione un usuario.");
            return;
        }
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblUsuarios.getModel();
        int id = (int) model.getValueAt(fila, 0);
        String username = (String) model.getValueAt(fila, 1);
        if (mostrarConfirmacion("¿Desactivar al usuario '" + username + "'?")) {
            try {
                controller.desactivarUsuario(id);
                mostrarMensaje("exito", "Usuario desactivado.");
                cargarTabla();
                toggleFormulario(false);
            } catch (Exception e) {
                mostrarMensaje("error", "Error: " + e.getMessage());
            }
        }
    }

    private void reactivarUsuario() {
        int fila = tblUsuarios.getSelectedRow();
        if (fila == -1) {
            mostrarMensaje("advertencia", "Seleccione un usuario.");
            return;
        }
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblUsuarios.getModel();
        int id = (int) model.getValueAt(fila, 0);
        String username = (String) model.getValueAt(fila, 1);
        if (mostrarConfirmacion("¿Reactivar al usuario '" + username + "'?")) {
            try {
                controller.reactivarUsuario(id);
                mostrarMensaje("exito", "Usuario reactivado.");
                cargarTabla();
                toggleFormulario(false);
            } catch (Exception e) {
                mostrarMensaje("error", "Error: " + e.getMessage());
            }
        }
    }

    private void seleccionarUsuario() {
        int fila = tblUsuarios.getSelectedRow();
        if (fila == -1) return;
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblUsuarios.getModel();

        String estado = (String) model.getValueAt(fila, 4);
        if ("Inactivo".equals(estado)) {
            mostrarMensaje("advertencia", "El usuario está inactivo. Use 'Reactivar' para habilitarlo.");
            return;
        }

        usuarioEnEdicion = (int) model.getValueAt(fila, 0);
        txtUsername.setText((String) model.getValueAt(fila, 1));
        cmbRol.setSelectedItem((String) model.getValueAt(fila, 2));
        chkActivo.setSelected(true);
        txtPassword.setText(""); // No mostrar contraseña al editar

        // Cargar empleados si hace falta y seleccionar el correspondiente
        String empleadoStr = (String) model.getValueAt(fila, 3);
        boolean found = false;
        for (int i = 0; i < cmbEmpleado.getItemCount(); i++) {
            String item = cmbEmpleado.getItemAt(i);
            if (item != null && item.contains(empleadoStr)) {
                cmbEmpleado.setSelectedIndex(i);
                found = true;
                break;
            }
        }
        if (!found) {
            // Intentar agregar el empleado actual al combo si no está
            if (controller.listarUsuarios() != null) {
                // Obtener el empleado desde el usuario
                var usuario = controller.listarUsuarios().stream()
                    .filter(u -> u.getIdUsuario() == usuarioEnEdicion)
                    .findFirst().orElse(null);
                if (usuario != null) {
                    String empItem = usuario.getIdEmpleado() + " - " + empleadoStr;
                    cmbEmpleado.addItem(empItem);
                    cmbEmpleado.setSelectedItem(empItem);
                }
            }
        }

        editando = true;
        btnGuardar.setText("Actualizar");
        toggleFormulario(true);
    }

